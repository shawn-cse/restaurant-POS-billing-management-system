export type ImportKind = 'menu' | 'ingredients';

export function templateCsv(kind: ImportKind, withExamples: boolean): string {
  const headers = kind === 'menu' ? MENU_HEADERS : INGREDIENT_HEADERS;
  const example = kind === 'menu' ? MENU_EXAMPLE : INGREDIENT_EXAMPLE;
  return toCsv([[...headers], ...(withExamples ? example : [])]);
}

export const templateFileName = (kind: ImportKind, withExamples: boolean) =>
  `${kind === 'menu' ? 'menu-items' : 'ingredients'}${withExamples ? '-example' : '-template'}.csv`;
